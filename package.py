# ------------------------------------------------------------ packaging

def make_plugin_tree():
    """Create the folder layout the FOMOD expects, so a build is installable
    the moment the .esp files are dropped in."""
    made = 0
    for style in STYLES.values():
        for module in MODULES:
            d = ROOT / "Plugins" / style / module
            d.mkdir(parents=True, exist_ok=True)
            keep = d / ".gitkeep"
            if not keep.exists():
                keep.write_text(
                    f"Drop {MODULES[module][0]} here after running "
                    f"GenerateQuestMarkers.pas with TAG_STYLE = "
                    f"'{'descriptive' if style == 'Descriptive' else 'compact'}'.\n",
                    encoding="utf-8")
                made += 1
    print(f"  prepared Plugins/ tree ({made} placeholders)")


def package(db):
    dist = ROOT / "dist"
    dist.mkdir(exist_ok=True)
    staging = dist / "staging"
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir()

    for d in ("fomod", "Documentation", "Database", "Scripts"):
        shutil.copytree(ROOT / d, staging / d)
    if (ROOT / "Plugins").exists():
        for style in STYLES.values():
            src = ROOT / "Plugins" / style
            if src.exists():
                shutil.copytree(src, staging / style)

    missing = [p for p in staging.rglob("*") if False]  # placeholder for future checks
    archive = dist / f"RadiantQuestMarker-{VERSION}"
    with zipfile.ZipFile(f"{archive}.zip", "w", zipfile.ZIP_DEFLATED) as z:
        for p in staging.rglob("*"):
            if p.is_file():
                z.write(p, p.relative_to(staging))
    shutil.rmtree(staging)
    print(f"  wrote {(Path('dist') / (archive.name + '.zip'))}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-zip", action="store_true")
    args = ap.parse_args()

    print("Radiant Quest Marker build")
    db = load_db()
    aliases = load_aliases()

    esp_count = sum(1 for q in db["quests"] if q["confidence"] in ("verified", "likely") and q["tag"])
    print(f"  database: {len(db['quests'])} entries, {esp_count} taggable by default")

    # write_tsv(db)
    write_quest_database(db, aliases)
    # write_module_config()  # preserved custom 2-step FOMOD installer
    write_info_xml()
    make_plugin_tree()
    if not args.no_zip:
        package(db)
    print("Done.")


if __name__ == "__main__":
    main()
