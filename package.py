def load_db():
    with open(ROOT / "Database" / "quests.json", encoding="utf-8") as fh:
        return json.load(fh)


def load_aliases():
    with open(ROOT / "Database" / "aliases.json", encoding="utf-8") as fh:
        return json.load(fh)


# ------------------------------------------------------------------ TSV

def write_tsv(db):
    out = [
        "# Generated by build/package.py - do not hand edit.",
        "# Source of truth: Database/quests.json",
        "# formID|editorID|originalName|tag|category|faction|dlc|repeatable|"
        "timed|settlementRelated|sourcePlugin|module|confidence|evidence",
    ]
    for q in db["quests"]:
        out.append("|".join([
            q["formID"] or "",
            q["editorID"] or "",
            q["originalName"],
            q["tag"] or "",
            q["category"],
            q["faction"],
            q["dlc"] or "",
            "true" if q["repeatable"] else "false",
            "true" if q["timed"] else "false",
            "true" if q["settlementRelated"] else "false",
            q["sourcePlugin"],
            q["module"] or "",
            q["confidence"],
            (q.get("evidence") or "").replace("|", "/"),
        ]))
    path = ROOT / "Database" / "quests.tsv"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"  wrote {path.relative_to(ROOT)} ({len(db['quests'])} rows)")


# ------------------------------------------------- QUEST_DATABASE.md

def write_quest_database(db, aliases):
    desc = aliases["styles"]["descriptive"]
    comp = aliases["styles"]["compact"]
    counts = {}
    for q in db["quests"]:
        counts[q["confidence"]] = counts.get(q["confidence"], 0) + 1

    L = [
        "# Quest Database",
        "",
        f"Generated from `Database/quests.json` by `build/package.py`. Target runtime: {db['targetRuntime']}.",
        "",
        "## Confidence states",
        "",
        "| State | Meaning | Tagged by default |",
        "| --- | --- | --- |",
        "| `verified` | Confirmed against local game records by `AuditQuests.pas`. | yes |",
        "| `likely` | Strong public evidence, not yet confirmed against records. | yes |",
        "| `unverified` | Listed for completeness only. | no |",
        "| `excluded` | Reviewed and deliberately left untagged. | never |",
        "",
        "### Current counts",
        "",
        "| State | Entries |",
        "| --- | --- |",
    ]
    for state in ("verified", "likely", "unverified", "excluded"):
        L.append(f"| {state} | {counts.get(state, 0)} |")

    L += [
        "",
        "> **Nothing in this file ships as `verified` out of the box.** Verification requires",
        "> reading the QUST records in your own install. Run `AuditQuests.pas` first; it",
        "> resolves the empty FormID and EditorID columns below and promotes entries whose",
        "> records actually carry radiant signals.",
        "",
    ]

    for dlc_key, heading in SOURCE_ORDER:
        rows = [q for q in db["quests"] if q["dlc"] == dlc_key]
        if not rows:
            continue
        L += ["", f"# {heading}", ""]
        factions = [f for f in FACTION_ORDER if any(r["faction"] == f for r in rows)]
        for fac in factions:
            frows = [r for r in rows if r["faction"] == fac]
            if len(factions) > 1:
                L += [f"## {fac}", ""]
            L += [
                "| Quest | FormID | EditorID | Category | Repeatable | Tag | Confidence |",
                "| --- | --- | --- | --- | --- | --- | --- |",
            ]
            for r in sorted(frows, key=lambda x: (x["confidence"] != "verified",
                                                  x["confidence"], x["originalName"])):
                tag_d = desc.get(r["tag"], "-") if r["tag"] else "-"
                tag_c = comp.get(r["tag"], "-") if r["tag"] else "-"
                tag_cell = "-" if tag_d == "-" else f"`{tag_d}` / `{tag_c}`"
                L.append(
                    f"| {r['originalName']} "
                    f"| {r['formID'] or '_pending audit_'} "
                    f"| {r['editorID'] or '_pending audit_'} "
                    f"| {r['category']} "
                    f"| {'yes' if r['repeatable'] else 'no'} "
                    f"| {tag_cell} "
                    f"| {r['confidence']} |"
                )
            L.append("")

    L += [
        "# Deliberately excluded",
        "",
        "Listed so the exclusions are auditable rather than invisible.",
        "",
        "| Quest | Source | Why excluded |",
        "| --- | --- | --- |",
    ]
    for r in db["quests"]:
        if r["confidence"] == "excluded":
            L.append(f"| {r['originalName']} | {r['sourcePlugin']} | {r['evidence']} |")

    L += [
        "",
        "# Rule-discovered quests",
        "",
        "The Minutemen settlement families are not enumerated by name here. Their display",
        "names contain text-replacement tokens such as `<Alias=Workshop>`, so the name a",
        "player sees is generated per settlement and is not a stable match key. They are",
        "discovered by EditorID family instead - see `Database/radiant_rules.json`,",
        "`radiantEditorIDPatterns`. `AuditQuests.pas` writes them into",
        "`output/quests.candidate.tsv` with real FormIDs from your install.",
        "",
        "# Known-empty categories",
        "",
        "| DLC | Radiant quests | Note |",
        "| --- | --- | --- |",
        "| Vault-Tec Workshop | 0 expected | The vault experiments are workshop mechanics, not repeatable QUST records. |",
        "| Contraptions Workshop | 0 expected | No quest content. |",
        "| Wasteland Workshop | 0 expected | No quest content. |",
        "",
    ]
    path = ROOT / "Documentation" / "QUEST_DATABASE.md"
    path.write_text("\n".join(L), encoding="utf-8")
    print(f"  wrote {path.relative_to(ROOT)}")


# ------------------------------------------------------------- FOMOD

def _files_block(module, style_key, indent):
    plugin = MODULES[module][0]
    folder = f"{STYLES[style_key]}/{module}"
    pad = " " * indent
    return (f'{pad}<files>\n'
            f'{pad}  <folder source="{folder}" destination="" priority="0" />\n'
            f'{pad}</files>\n')


